/**
 * 只判断当前触发消息是否明确要求机器人产出图片。它是 generate_image 的
 * 执行侧门禁事实来源，因此策略有意保守：模糊表达宁可退回文字回应，也不
 * 让模型依据历史上下文或自行发挥发起高成本生图。
 *
 * 调用方还必须确认消息是在回复/@机器人；群聊里对别人说的同一句请求不算
 * 对机器人的明确调用。这里不接收整份聊天记录，避免旧消息污染判断。
 */
export function hasExplicitImageGenerationIntent(raw: string | undefined): boolean {
  if (!raw) return false;
  const text: string = raw.replace(/\s+/g, " ").trim().toLowerCase();
  if (!text) return false;

  // 询问能力、讨论功能或索要提示词都不是要求本轮真正生成图片。
  // “帮我/给我”等委托词会把“你能……”从能力询问变成实际请求，不能被
  // 第一条泛能力规则误伤；功能讨论与 prompt 请求则无条件拒绝。
  const hasDelegationCue: boolean = /(?:帮我|帮忙|给我|替我|为我|麻烦(?:你)?|请(?!问))/i.test(text);
  if (
    (!hasDelegationCue &&
      /(?:你|机器人|bot|ai).{0,6}(?:会不会|会|能否|能|可以|是否|支持|有没有).{0,8}(?:生图|出图|画图|绘图|生成图片).{0,4}(?:吗|么|嘛|？|\?)/i.test(text)) ||
    (!hasDelegationCue &&
      /(?:^|[\s，。！？、；：,.!?;:])(?:请问\s*)?(?:我|你)?\s*(?:可以|能否|能|是否|支持).{0,8}(?:生图|出图|画图|绘图|生成图片)\s*(?:吗|么|嘛)?\s*(?:？|\?)?$/i.test(text)) ||
    /(?:这个|该|此)?\s*(?:功能|能力|工具).{0,8}(?:可以|能否|能|是否|支持).{0,8}(?:生图|出图|画图|绘图|生成图片).{0,4}(?:吗|么|嘛|？|\?)/i.test(text) ||
    /(?:生图|出图|画图|绘图|图片生成).{0,6}(?:功能|能力|工具).{0,6}(?:吗|么|嘛|？|\?|如何|怎么)/i.test(text) ||
    /(?:写|改|优化|润色|翻译|分析|讨论|提供).{0,8}(?:生图|出图|绘图|图片生成)?\s*(?:prompt|提示词)/i.test(text) ||
    /\b(?:write|create|generate|improve|translate)\b.{0,32}\b(?:prompt|instructions?)\b/i.test(text)
  ) {
    return false;
  }

  // 中文常见的直接请求：生图/出图/做图，或明确要求制作某类视觉成品。
  if (/(?:^|[\s，。！？、；：,.!?;:])(?:请|麻烦|帮我|帮忙|给我|替我|为我)?\s*(?:生图|出图|做图|画图|绘图)(?:$|[\s，。！？、；：,.!?;:]|一下|一张|一个)/i.test(text)) {
    return true;
  }
  if (/(?:请|麻烦|帮我|帮忙|给我|替我|为我|能不能|可以|来)?\s*(?:生成|制作|设计|创作|做|整|来).{0,32}(?:图片|图像|插画|海报|壁纸|视觉稿|头像|封面|配图|照片|漫画|画作|图)/i.test(text)) {
    return true;
  }
  if (/(?:^|[\s，。！？、；：,.!?;:])(?:请|麻烦|帮我|帮忙|给我|替我|为我|能不能|可以)?\s*(?:画|重画|绘制)(?:成|一|个|只|张|幅|些|几|点|下|一下|份)/i.test(text)) {
    return true;
  }
  if (/(?:给我|帮我|来)(?:一|几|个|张|幅|套|版|些)*\s*(?:图片|图像|插画|海报|壁纸|头像|封面|配图|漫画|画)/i.test(text)) {
    return true;
  }
  // 回复一份媒体时常见的“把/按这个重画、做成海报”表达。
  if (/(?:把|按|按照|照着|根据).{0,24}(?:画成|重画|绘制|生成(?:成)?|做成).{0,24}(?:图|图片|插画|海报|壁纸|头像|封面|漫画|风格)?/i.test(text)) {
    return true;
  }

  // 英文与日文只收明确的创作动词，能力询问已在上方先行排除。
  if (/\b(?:draw|paint)\s+(?:me\s+)?(?:a|an|the|this|that|my|some)\b/i.test(text)) return true;
  if (/\b(?:generate|create|make|design)\b.{0,40}\b(?:image|picture|poster|wallpaper|illustration|artwork|portrait|cover)\b/i.test(text)) return true;
  return /(?:画像|イラスト|ポスター|壁紙).{0,16}(?:生成して|作って|描いて)|(?:生成して|作って|描いて).{0,16}(?:画像|イラスト|ポスター|壁紙)/u.test(text);
}
